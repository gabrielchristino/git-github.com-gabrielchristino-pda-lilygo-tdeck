"""Generate the C++ profile-3 lexical table from the Python specification."""
from pathlib import Path
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[2]/'.pio-tools/ai'))
from text_features import FOLDS, SHORT

path = Path(__file__).resolve().parents[2] / 'src/core/intent_pt_folds.inc'
payload = '// Generated by tools/ai/generate_pt_folds.py; do not hand-edit.\n'
payload += 'static const char *const ptFolds[][2] = {\n'
payload += ''.join(f'    {{"{key}", "{value}"}},\n' for key, value in sorted(FOLDS.items()))
payload += '};\n'
path.write_bytes(payload.encode('utf-8'))
print(path)
short_path=path.with_name('intent_pt_short.inc')
short_payload='// Generated by tools/ai/generate_pt_folds.py; profile 5 only.\n'
short_payload+='static const char *const ptShort[][2] = {\n'
short_payload+=''.join(f'    {{"{key}", "{value}"}},\n' for key,value in sorted(SHORT.items()))
short_payload+='};\n'
short_path.write_bytes(short_payload.encode('utf-8'))
print(short_path)
