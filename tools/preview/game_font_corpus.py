"""Collect C++ game string literals for the native renderer's font audit."""
import argparse
import ast
import json
from pathlib import Path
import re

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--output', type=Path, required=True)
args = parser.parse_args()
root = Path(__file__).resolve().parents[2]
sources = [root / 'src' / folder / name
           for folder in ('apps', 'core')
           for name in ('games.cpp', 'more_games.cpp')]
tokens = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"', re.S)
strings = set()
for source in sources:
    for token in tokens.findall(source.read_text(encoding='utf-8')):
        if token.startswith('"'):
            strings.add(ast.literal_eval(token))
assert strings
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text(
    '// Generated by game_font_corpus.py; do not edit.\n'
    'static const char *const game_text_corpus[] = {\n'
    + ''.join('    ' + json.dumps(s, ensure_ascii=False) + ',\n'
              for s in sorted(strings))
    + '};\n', encoding='utf-8')
